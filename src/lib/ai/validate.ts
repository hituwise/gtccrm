import { generateReply } from './generate'
import type { AiConfig } from './types'
import type { TenantProductConfig } from '@/lib/ai/actions/types'
import type { CalendarActionResult } from '@/lib/ai/actions/action-runner'
import type { PersistedConversationState } from './conversation-state'

/**
 * Cheap liveness + auth check: one tiny generation against the
 * configured provider/model with the caller's key. Throws `AiError`
 * (invalid_key / rate_limited / network / timeout) on failure, resolves
 * on success. Used by the settings "Test key" button and before
 * persisting a config — the same "verify before save" discipline the
 * WhatsApp config uses with Meta.
 */
export async function validateAiCredentials(config: AiConfig): Promise<void> {
  await generateReply({
    config,
    systemPrompt: 'You are a connectivity check. Reply with the single word: OK.',
    messages: [{ role: 'user', content: 'ping' }],
  })
}

export interface OutputValidationArgs {
  draftText: string
  knowledgeExcerpts?: string[]
  tenantProducts?: TenantProductConfig[]
  toolResults?: CalendarActionResult | null
  conversationState?: PersistedConversationState | null
  lastBotMessage?: string | null
}

export interface OutputValidationResult {
  isValid: boolean
  reason?: string
  isRepetition?: boolean
}

function calculateTokenSimilarity(a: string, b: string): number {
  const normA = a.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').trim()
  const normB = b.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').trim()
  if (normA === normB) return 1
  if (!normA || !normB) return 0

  const tokensA = new Set(normA.split(/\s+/).filter(Boolean))
  const tokensB = new Set(normB.split(/\s+/).filter(Boolean))
  if (tokensA.size === 0 || tokensB.size === 0) return 0

  let common = 0
  for (const t of tokensA) {
    if (tokensB.has(t)) common++
  }
  const total = new Set([...tokensA, ...tokensB]).size
  return total > 0 ? common / total : 0
}

/**
 * Output Validator:
 * 1. Anti-repetition: rejects drafts that repeat or closely match the last bot message.
 * 2. Unverified video links: rejects links not generated by a calendar tool or defined on tenant products.
 * 3. Fake booking confirmation: rejects claiming an appointment is booked if booking tool did not succeed.
 * 4. Cross-tenant leakage: rejects mentioning foreign tenant products not in the tenant's catalogue or KB.
 */
export function validateReplyOutput(args: OutputValidationArgs): OutputValidationResult {
  const {
    draftText,
    knowledgeExcerpts = [],
    tenantProducts = [],
    toolResults,
    conversationState,
    lastBotMessage,
  } = args

  if (!draftText || !draftText.trim()) {
    return { isValid: false, reason: 'Empty response draft' }
  }

  // 1. Anti-repetition check (exempt legitimate confirmed booking announcements)
  const isConfirmedBooking =
    Boolean(toolResults?.action === 'book_appointment' && toolResults?.success) ||
    Boolean(toolResults?.action === 'reschedule_appointment' && toolResults?.success);

  if (!isConfirmedBooking && lastBotMessage && lastBotMessage.trim()) {
    const similarity = calculateTokenSimilarity(draftText, lastBotMessage)
    if (similarity >= 0.85) {
      return {
        isValid: false,
        reason: 'Response equals or closely matches the previous bot message',
        isRepetition: true,
      }
    }
  }

  // 2. Unverified meeting link check
  const linkMatch = draftText.match(/https?:\/\/(?:meet\.google\.com|zoom\.us|teams\.microsoft\.com)\/[a-zA-Z0-9_\-]+/i)
  if (linkMatch) {
    const linkFound = linkMatch[0]
    const toolMeetLink =
      toolResults?.meetLink ||
      (toolResults?.action === 'book_appointment' && toolResults?.success ? toolResults?.meetLink : null)
    const productStaticLink = tenantProducts.some((p) => p.meetingLink && linkFound.includes(p.meetingLink))

    if (!toolMeetLink && !productStaticLink) {
      return {
        isValid: false,
        reason: 'Response contains an unverified video meeting link not confirmed by booking tool',
      }
    }
  }

  // 3. Fake booking confirmation check
  const claimsBookingConfirmed = /\b(?:is booked|has been booked|is confirmed|booking confirmed|appointment confirmed|scheduled on your calendar)\b/i.test(draftText)
  if (claimsBookingConfirmed) {
    const hasSuccessfulBooking =
      (toolResults?.action === 'book_appointment' && toolResults?.success) ||
      conversationState?.state === 'BOOKED'
    if (!hasSuccessfulBooking) {
      return {
        isValid: false,
        reason: 'Response claims booking is confirmed without successful calendar booking',
      }
    }
  }

  // 4. Cross-tenant isolation check
  // Verify draft does not pitch foreign products that are neither in active tenantProducts nor KB
  const tenantContextText = (
    tenantProducts.map((p) => `${p.name} ${p.productServiceId} ${p.description || ''}`).join(' ') +
    ' ' +
    knowledgeExcerpts.join(' ')
  ).toLowerCase()

  const knownTenantSignatures = [
    { label: 'Lead Pilot', pattern: /\blead\s*pilot\b/i },
    { label: 'My Abacus Academy', pattern: /\bmy\s*abacus\s*academy\b/i },
    { label: 'Abacus Mental Math', pattern: /\babacus\s*mental\s*math\b/i },
    { label: 'Rubik\'s Cube Program', pattern: /\brubik'?s\s*cube\s*program\b/i },
    { label: 'Teacher Training Course (GTC)', pattern: /\bteacher\s*training\s*course\b/i },
  ]

  for (const sig of knownTenantSignatures) {
    if (sig.pattern.test(draftText) && !sig.pattern.test(tenantContextText)) {
      return {
        isValid: false,
        reason: `Response mentions product "${sig.label}" not configured in active tenant catalogue or knowledge base`,
      }
    }
  }

  return { isValid: true }
}
